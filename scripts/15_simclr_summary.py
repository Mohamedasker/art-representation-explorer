#!/usr/bin/env python3
"""Table of all SimCLR runs (dataset x aug set): run dir, wandb, epochs, status, last kNN / linear probe accuracy.
    python scripts/15_simclr_summary.py [--out docs/simclr_runs.md]"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--runs-dir", default="runs")
ap.add_argument("--out", default="docs/simclr_runs.md")
a = ap.parse_args()

rows = []
for d in sorted(Path(a.runs_dir).glob("*_simclr_*")):
    cfg_f = d / "config.json"
    if not cfg_f.exists() or "smoke" in d.name:
        continue
    cfg = json.loads(cfg_f.read_text())
    st = json.loads((d / "status.json").read_text()) if (d / "status.json").exists() else {}
    last = {}
    mf = d / "metrics.jsonl"
    if mf.exists():
        for line in mf.read_text().splitlines():
            m = json.loads(line)
            if "val/knn_acc" in m:
                last = m
    wb = json.loads((d / "wandb_info.json").read_text()) if (d / "wandb_info.json").exists() else {}
    url = wb.get("url") or (f"offline `{wb['id']}` (sync pending)" if wb else "-")
    ep = (last.get("step", st.get("step", 0)) or 0) / cfg["steps_per_epoch"]
    rows.append((cfg["dataset"], cfg["aug_set"], d.name, f"{st.get('epochs', ep):.0f}/{cfg['args']['epochs']}",
                 st.get("status", "running/queued"), last.get("val/knn_acc"), last.get("val/linear_acc"), url))
rows.sort()
f = lambda x: "-" if x is None else f"{100 * x:.1f}"
out = ["| dataset | aug set | run dir | epochs | status | kNN % | linear % | wandb |", "|---|---|---|---|---|---|---|---|"]
out += [f"| {r[0]} | {r[1]} | `runs/{r[2]}` | {r[3]} | {r[4]} | {f(r[5])} | {f(r[6])} | {r[7]} |" for r in rows]
text = "\n".join(out)
print(text)
if a.out:
    Path(a.out).parent.mkdir(exist_ok=True)
    Path(a.out).write_text("# SimCLR runs\n\nGenerated by `scripts/15_simclr_summary.py` "
                           "(probe = style-label accuracy on frozen encoder features, 10k train -> 4k test images).\n\n" + text + "\n")
